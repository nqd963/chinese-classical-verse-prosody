def main() -> None:
    out = skill_data_dir()
    if "--out" in sys.argv:
        out = sys.argv[sys.argv.index("--out") + 1]
    ps_path = os.path.join(out, "pingshui.json")
    with open(ps_path, "r", encoding="utf-8") as fh:
        ps = json.load(fh)
    known = set(ps["chars"])

    t2s = {k: v for k, v in T2S.items() if k != v}
    hit = {k: v for k, v in t2s.items() if v in known}
    miss_target = {k: v for k, v in t2s.items() if v not in known}
    alias = {k: v for k, v in ALIAS.items() if v in known}
    alias_miss = {k: v for k, v in ALIAS.items() if v not in known}

    doc = {
        "schema_version": "1.0",
        "purpose": "查询层繁简归一（裁决书 §8）。平水韵表本体为简体，不改表；本表仅在查表前把繁体/异体归一到韵表字形。",
        "source": {"note": "繁简对应据通行《简化字总表》常见字，异体对照据通行字书；已逐条对平水韵表实测",
                   "copyright": "公版工具性映射"},
        "meta": {"t2s_total": len(t2s), "t2s_effective": len(hit),
                 "t2s_target_absent_from_table": len(miss_target),
                 "alias_effective": len(alias), "alias_target_absent": len(alias_miss)},
        "t2s": hit,
        "alias": alias,
        "t2s_ineffective": miss_target,
        "alias_ineffective": alias_miss,
    }
    dump_json(doc, os.path.join(out, "trad_simp.json"))
    sys.stdout.write("t2s=%d effective=%d alias=%d effective=%d\n" % (
        len(t2s), len(hit), len(ALIAS), len(alias)))


if __name__ == "__main__":
    main()
